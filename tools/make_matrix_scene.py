"""Builds the backdrop scene, mirrored half-width katakana columns falling on
black, and writes it to ../hooks/scene.js.

The motion is CSS keyframes inside the SVG's own <style>, the way the desktop
app animates a theme's scene. Run it again after changing anything here:

    python3 tools/make_matrix_scene.py
"""
import json
import os
import random

random.seed(11)
W, H = 1600, 1000
GLYPHS = ''.join(chr(c) for c in range(0xFF66, 0xFF9E))  # half-width katakana only
COLS, LEN, STEP = 48, 24, 24
TRAVEL_FROM, TRAVEL_TO = -LEN * STEP, H + 40

columns, rules = [], []
gap = W / COLS
for i in range(COLS):
    x = round(i * gap + gap / 2 + random.uniform(-5, 5))
    dur = round(random.uniform(4.5, 11), 2)
    delay = round(-random.uniform(0, dur), 2)
    alpha = round(random.uniform(.35, .85), 2)
    size = random.choice((20, 22, 24, 24, 26))
    rules.append(f'.k{i}{{animation:fall {dur}s linear {delay}s infinite;opacity:{alpha}}}')
    spans = []
    for j in range(LEN):
        op = round(0.06 + 0.94 * (j / (LEN - 1)) ** 2.2, 2)
        head = ' class="h"' if j == LEN - 1 else ''
        spans.append(f'<tspan x="{x}" dy="{STEP}" opacity="{op}"{head}>{random.choice(GLYPHS)}</tspan>')
    columns.append(
        f'<g class="k{i}"><text font-size="{size}" text-anchor="middle" '
        f'transform="matrix(-1 0 0 1 {2 * x} 0)">{"".join(spans)}</text></g>')

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">
<defs>
<radialGradient id="bg" cx=".5" cy=".4" r=".85"><stop offset="0" stop-color="#03110a"/><stop offset="1" stop-color="#000"/></radialGradient>
<radialGradient id="vig" cx=".5" cy=".5" r=".75"><stop offset=".6" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".8"/></radialGradient>
<filter id="glow" x="-50%" y="-10%" width="200%" height="120%"><feGaussianBlur stdDeviation="2.2" result="b"/><feMerge><feMergeNode in="b"/><feMergeNode in="SourceGraphic"/></feMerge></filter>
</defs>
<style>
text{{font-family:"Hiragino Sans","Hiragino Kaku Gothic ProN","MS Gothic","Noto Sans CJK JP",Menlo,monospace;font-weight:600;fill:#22ff66}}
.h{{fill:#dcffe8}}
@keyframes fall{{from{{transform:translateY({TRAVEL_FROM}px)}}to{{transform:translateY({TRAVEL_TO}px)}}}}
{chr(10).join(rules)}
</style>
<rect width="{W}" height="{H}" fill="url(#bg)"/>
<g filter="url(#glow)">
{chr(10).join(columns)}
</g>
<rect width="{W}" height="{H}" fill="url(#vig)"/>
</svg>'''

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, '..', 'hooks', 'scene.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/make_matrix_scene.py; edit that file, not this one.\n')
    f.write('export const SCENE = ' + json.dumps(svg, ensure_ascii=False) + '\n')
print('scene chars', len(svg))
